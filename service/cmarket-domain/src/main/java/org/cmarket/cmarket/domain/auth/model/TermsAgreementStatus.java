package org.cmarket.cmarket.domain.auth.model;

/**
 * 약관 동의 상태 (#1088)
 *
 * ⚠️ **NULL 로 두지 않으려고 만든 값이다.** NULL 은 「동의를 받은 적 없다」는 *사실*과
 *    「아직 안 채웠다·마이그레이션이 실패했다·버그다」를 **구분하지 못한다.**
 *    사실을 값으로 적어야 나중에 이 칸을 보고 판단할 수 있다.
 *
 * ⚠️ **PRE_TERMS 를 「동의함」으로 바꾸지 마라.** 동의한 적 없는 사람을 동의했다고
 *    기록하면, 증명하려고 만든 기록이 오히려 불리한 증거가 된다.
 */
public enum TermsAgreementStatus {
    /** 가입 화면에서 동의를 받았다. */
    AGREED,
    /**
     * 동의를 받은 적이 없다.
     *
     * ⚠️ **두 경우가 이 값으로 섞인다.** 알고 두는 것이다.
     *
     *   ① 약관 도입(2026-08-25) 전에 가입한 사람
     *   ② 소셜로 첫 로그인만 하고 **프로필 완성(=동의) 화면을 안 끝낸** 사람
     *      소셜은 첫 로그인에 계정이 먼저 생긴다
     *      (GoogleAuthService · OAuth2UserPersistenceService 가 User 를 만든다)
     *      그 시점에는 아직 동의를 안 받았으므로 이 값이 맞다
     *
     * 둘을 갈라야 하면 `createdAt` 을 약관 도입일과 견주면 된다. 갈라야 할 일이 생기기
     * 전에 값을 늘리지 않는다 — 값 이름은 DB 에 글자로 들어가서 나중에 바꾸기 번거롭다.
     */
    PRE_TERMS
}
